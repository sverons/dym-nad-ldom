    private static func card(
        _ id: String,
        _ role: PlayerRole,
        _ name: String,
        _ value: Int,
        _ colors: [EvidenceColor],
        _ kind: CardKind,
        _ actionTitle: String,
        _ actionDetail: String,
        _ quote: String,
        joker: Bool = false,
        reaction: Bool = false
    ) -> CardDefinition {
        CardDefinition(
            id: id,
            role: role,
            name: name,
            value: min(4, max(1, value)),
            valueColors: colors,
            isJoker: joker || colors.isEmpty,
            kind: kind,
            actionTitle: actionTitle,
            actionDetail: actionDetail,
            quote: quote,
            isReaction: reaction
        )
    }
