  function photoFingerprint(path) {
    const normalized = String(path || '').replace(/^\.\//, '');
    return window.NovogramPhotoFingerprints?.[normalized] || normalized;
  }

  function resolvePostImageKey(post) {
    if (post?.image?.src) return photoFingerprint(post.image.src);
    const category = post?.image?.category || 'city';
    const photo = Number(post?.image?.photo);
    const variant = Number.isFinite(photo) && photo > 0
      ? ((Math.floor(photo) - 1) % 4) + 1
      : 1;
    return photoFingerprint(`assets/novogram/${category}-${variant}.jpg`);
  }

  function buildImagePool(reserved) {
    const pool = [];
    const availableFingerprints = new Set();
    PHOTO_CATEGORIES.forEach(category => {
      for (let photo = 1; photo <= 4; photo++) {
        const path = `assets/novogram/${category}-${photo}.jpg`;
        const fingerprint = photoFingerprint(path);
        if (!reserved.has(fingerprint) && !availableFingerprints.has(fingerprint)) {
          availableFingerprints.add(fingerprint);
          pool.push({ category, photo, fingerprint });
        }
      }
    });
    return pool;
  }

  function claimImage(pool, preferredCategory) {
    const preferredIdx = pool.findIndex(item => item.category === preferredCategory);
    if (preferredIdx >= 0) return pool.splice(preferredIdx, 1)[0];
    return pool.shift() || null;
  }

  function dedupePostsByImage(posts) {
    const seen = new Set();
    const unique = [];
    const priority = (post) => {
      if (post.prepared) return 0;
      if (!post.filler) return 1;
      return 2;
    };
    [...posts]
      .sort((a, b) => priority(a) - priority(b))
      .forEach(post => {
        const key = resolvePostImageKey(post);
        if (seen.has(key)) return;
        seen.add(key);
        unique.push(post);
      });
    return unique;
  }

  function build(reservedKeys) {
    const users = [];
    const posts = [];
    const fillerIds = [];
    const pool = buildImagePool(reservedKeys);

    PROFILES.forEach((profile, index) => {
      fillerIds.push(profile.id);
      const rng = mulberry32(1000 + index * 97);
      const profilePosts = [];
      const category = profile.category || 'city';
      const maxPosts = Math.min(profile.captions.length, 4);

      for (let i = 0; i < maxPosts; i++) {
        const claimed = claimImage(pool, category);
        if (!claimed) break;

        const visual = GRADIENTS[(index + i) % GRADIENTS.length];
        const label = profile.labels[i % profile.labels.length];
        const postId = `${profile.id}_p${i + 1}`;
        const commentPool = COMMENT_BY_CATEGORY[category] || COMMENT_BY_CATEGORY.city;
        const commentCount = 2 + Math.floor(rng() * 3);
        const comments = [];
        for (let c = 0; c < commentCount; c++) {
          let authorIdx = Math.floor(rng() * PROFILES.length);
          if (authorIdx === index) authorIdx = (authorIdx + 1) % PROFILES.length;
          comments.push({
            id: `${postId}_c${c + 1}`,
            userId: PROFILES[authorIdx].id,
            text: pick(rng, commentPool),
            time: pick(rng, TIME_LABELS.slice(0, 8)),
          });
        }

        profilePosts.push({
          id: postId,
          userId: profile.id,
          filler: true,
          news: true,
          image: {
            category: claimed.category,
            photo: claimed.photo,
            gradient: visual.gradient,
            emoji: visual.emoji,
            label,
          },
          caption: profile.captions[i],
          likes: 20 + Math.floor(rng() * 480),
          time: TIME_LABELS[i % TIME_LABELS.length],
          comments,
        });
      }

      users.push({
        id: profile.id,
        username: profile.username,
        name: profile.name,
        bio: profile.bio,
        avatar: profile.name.trim().charAt(0).toUpperCase(),
        color: COLORS[index % COLORS.length],
        posts: profilePosts.length,
        followers: 120 + index * 37,
        following: 40 + (index % 20) * 3,
        filler: true,
      });
      posts.push(...profilePosts);
    });

    return { users, posts, fillerIds };
  }

  const reservedKeys = new Set((seed.posts || []).map(resolvePostImageKey));
  const built = build(reservedKeys);
  seed.fillerAccountIds = built.fillerIds;
  seed.users = [...seed.users, ...built.users];
  seed.posts = dedupePostsByImage([...seed.posts, ...built.posts]);

  const postCounts = {};
  seed.posts.forEach(post => {
    postCounts[post.userId] = (postCounts[post.userId] || 0) + 1;
  });
  seed.users.forEach(user => {
    if (Object.prototype.hasOwnProperty.call(postCounts, user.id) || user.filler) {
      user.posts = postCounts[user.id] || 0;
    }
  });
