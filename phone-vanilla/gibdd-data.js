const GIBDD_CHARACTER_IDS = [
  'sergey', 'anna', 'veronika', 'zhanna', 'viktor', 'natalia', 'kristina', 'igor',
  'artur', 'likhachev', 'tikhonov', 'pavel', 'miya', 'morozov', 'krylov',
  'elena-sokolova', 'pavel-sokolov', 'oleg-sokolov', 'maria-egorova', 'inna-krestova',
  'dmitry-nazarov', 'ilya-lontsov', 'nikolai-ivanov', 'oksana-ivanova',
];

const GIBDD_FULL_SEED = RAW_GIBDD_SEED.map((car, index) => {
  const withId = { ...car, characterId: GIBDD_CHARACTER_IDS[index] };
  return typeof CharactersDB !== 'undefined'
    ? CharactersDB.enrichGibddCar(withId)
    : withId;
});

let GIBDD_STORAGE_KEY = 'dym_gibdd_cars_v4';
let GIBDD_SEED = GIBDD_FULL_SEED.map(car => ({ ...car }));

function normalizePlate(plate) {
  return String(plate || '').replace(/\s+/g, '').toUpperCase();
}

function emptyCar() {
  return {
    brand: '',
    plateNumber: '',
    year: new Date().getFullYear(),
    color: '',
    category: 'B',
    vin: '',
    bodyNumber: '',
    engineNumber: '',
    engineVolume: 0,
    power: '',
    ptsNumber: '',
    accidents: 'Нет',
    photo: '',
    ownerName: '',
    ownerBirthDate: '',
    ownerAddress: '',
  };
}

function cloneSeed(seed) {
  return seed.map(car => ({ ...car }));
}

function loadCars() {
  try {
    const raw = localStorage.getItem(GIBDD_STORAGE_KEY);
    if (!raw) {
      saveCars(cloneSeed(GIBDD_SEED));
      return cloneSeed(GIBDD_SEED);
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : cloneSeed(GIBDD_SEED);
  } catch {
    return cloneSeed(GIBDD_SEED);
  }
}

function saveCars(cars) {
  localStorage.setItem(GIBDD_STORAGE_KEY, JSON.stringify(cars));
}

function searchCarByPlate(plate) {
  const query = normalizePlate(plate);
  if (!query) return null;
  return loadCars().find(car => normalizePlate(car.plateNumber) === query) || null;
}

function addCar(car) {
  const cars = loadCars();
  const entry = {
    ...emptyCar(),
    ...car,
    id: `car-${Date.now()}`,
    plateNumber: String(car.plateNumber || '').toUpperCase(),
  };
  cars.push(entry);
  saveCars(cars);
  return entry;
}

function updateCar(car) {
  const cars = loadCars();
  const index = cars.findIndex(item => item.id === car.id);
  if (index === -1) return null;
  cars[index] = {
    ...cars[index],
    ...car,
    plateNumber: String(car.plateNumber || '').toUpperCase(),
  };
  saveCars(cars);
  return cars[index];
}

function deleteCar(id) {
  const cars = loadCars().filter(car => car.id !== id);
  saveCars(cars);
}

function resetCarsToSeed() {
  saveCars(cloneSeed(GIBDD_SEED));
  return cloneSeed(GIBDD_SEED);
}

function configure(storageKey, seed) {
  if (storageKey) GIBDD_STORAGE_KEY = storageKey;
  if (seed) GIBDD_SEED = cloneSeed(seed);
}

window.GIBDD_FULL_SEED = GIBDD_FULL_SEED;

window.GibddDB = {
  configure,
  loadCars,
  saveCars,
  searchCarByPlate,
  addCar,
  updateCar,
  deleteCar,
  emptyCar,
  resetCarsToSeed,
  normalizePlate,
};
